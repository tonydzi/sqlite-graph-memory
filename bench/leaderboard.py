# -*- coding: utf-8 -*-
"""leaderboard.py — regenerate bench/LEADERBOARD.md from bench/results/*.json.

Never edit LEADERBOARD.md by hand: CI regenerates it and fails the build on any difference.
Rows are sorted by recall@5; there is no single combined score, because a system that
retrieves well and confabulates on missing facts is not "a bit worse" than one that
abstains, it is a different kind of risk. Read the columns.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import bench_core as bc  # noqa: E402

COLS = [('recall@5', 'R@5'), ('recall@10', 'R@10'), ('answer_acc', 'answer'),
        ('citation_verbatim', 'verbatim cite'), ('citation_faithful', 'faithful quotes'),
        ('abstain_correct', 'abstains when absent'), ('false_abstain', 'false abstain ↓')]
RECALL_CLASSES = ['fact', 'bridge', 'paraphrase', 'paraphrase_bridge', 'temporal']
ABSTAIN_CLASSES = ['absent_entity', 'absent_attribute']


def f(x):
    return '–' if x is None else '%.2f' % x


def render():
    rs = [json.loads(p.read_text(encoding='utf-8')) for p in sorted(bc.RESULTS.glob('*.json'))]
    rs.sort(key=lambda r: (-(r['metrics']['overall']['recall@5'] or 0), r['system']['name']))
    n = rs[0]['metrics']['overall'] if rs else {}
    L = ['# Leaderboard — memory-bench v%s' % bc.BENCH_VERSION, '',
         '<!-- generated by bench/leaderboard.py from bench/results/*.json; do not edit by hand -->', '',
         'Synthetic vault: %s notes · %s questions (%s answerable, %s with no answer in the vault). '
         'How to read and how to add your system: [README](README.md) · [CONTRIBUTING](CONTRIBUTING.md).'
         % (len(list(bc.VAULT.glob('*.md'))), n.get('n', '?'), n.get('n_answerable', '?'), n.get('n_unanswerable', '?')),
         '',
         '| system | ' + ' | '.join(h for _, h in COLS) + ' | CI-reproduced | by |',
         '|---|' + '---:|' * len(COLS) + ':---:|---|']
    for r in rs:
        o, s = r['metrics']['overall'], r['system']
        L.append('| [%s](%s) `%s` | %s | %s | %s |' % (
            s['name'], s['url'], s['version'], ' | '.join(f(o[k]) for k, _ in COLS),
            'yes' if r['reproduce']['in_ci'] else 'self-reported', r['submitted_by']))
    L += ['', '## Recall@5 by question class', '',
          '| system | ' + ' | '.join(RECALL_CLASSES) + ' |', '|---|' + '---:|' * len(RECALL_CLASSES)]
    for r in rs:
        b = r['metrics']['by_class']
        L.append('| %s | %s |' % (r['system']['name'], ' | '.join(f(b.get(c, {}).get('recall@5')) for c in RECALL_CLASSES)))
    L += ['', '## Abstention by question class (share of unanswerable questions left unanswered)', '',
          '| system | ' + ' | '.join(ABSTAIN_CLASSES) + ' |', '|---|' + '---:|' * len(ABSTAIN_CLASSES)]
    for r in rs:
        b = r['metrics']['by_class']
        L.append('| %s | %s |' % (r['system']['name'], ' | '.join(f(b.get(c, {}).get('abstain_correct')) for c in ABSTAIN_CLASSES)))
    L += ['', '## Notes from the submitters', '']
    for r in rs:
        if r.get('notes'):
            L.append('- **%s** — %s' % (r['system']['name'], r['notes']))
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    (HERE / 'LEADERBOARD.md').write_text(render(), encoding='utf-8', newline='\n')
    print('wrote bench/LEADERBOARD.md')
